def hex_to_rgb(h):
    h = h.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def argb(hex_color, alpha=255):
    r, g, b = hex_to_rgb(hex_color)
    a = max(0, min(255, int(alpha)))
    return ((a & 0xFF) << 24) | ((r & 0xFF) << 16) | ((g & 0xFF) << 8) | (b & 0xFF)


